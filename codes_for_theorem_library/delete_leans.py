def batch_delete_lemmas(target_list_str):
    if not os.path.isdir(THEOREMS_DIR):
        print(f"❌ 错误: 找不到目录 {THEOREMS_DIR}")
        return

    # 解析列表，提取出文件名
    # 逻辑：取最后一段（如 lemma_10009），加上 .lean 后缀
    lines = target_list_str.strip().split('\n')
    files_to_delete = []
    for line in lines:
        line = line.strip()
        if line.startswith("- Aesop.theorems."):
            lemma_name = line.replace("- Aesop.theorems.", "")
            files_to_delete.append(f"{lemma_name}.lean")

    print(f"准备检查并删除 {len(files_to_delete)} 个文件...")

    deleted_count = 0
    not_found_count = 0

    for filename in files_to_delete:
        file_path = os.path.join(THEOREMS_DIR, filename)
        
        if os.path.exists(file_path):
            try:
                os.remove(file_path)
                print(f"✅ 已删除: {filename}")
                deleted_count += 1
            except Exception as e:
                print(f"❌ 删除失败 {filename}: {e}")
        else:
            # print(f"ℹ️ 未找到文件: {filename}")
            not_found_count += 1

    print("\n--- 任务总结 ---")
    print(f"成功删除: {deleted_count} 个文件")
    print(f"未找到: {not_found_count} 个文件")
    print("提示: 别忘了重新运行更新 theorems.lean 的脚本，以移除失效的 import！")

